const assert=require('node:assert/strict'),path=require('node:path');
const {chromium}=require(process.env.EMBER_PLAYWRIGHT_MODULE);
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.EMBER_BROWSER_EXECUTABLE});
  const hostErrors=[];let page,mobile;
  try{
    page=await browser.newPage({viewport:{width:1500,height:1000}});
    page.setDefaultTimeout(30000);page.on('pageerror',error=>hostErrors.push(error.message));
    const view=id=>require('./workspace_browser').view(page,id);
    const state=()=>page.evaluate(async()=>await (await fetch('/api/state',{headers:{'X-Ember-Token':sessionStorage.getItem('ember-token')}})).json());
    await require('./workspace_browser').stubPlanBuild(page);
    await page.goto(process.env.EMBER_BROWSER_URL+'#'+process.env.EMBER_BROWSER_TOKEN);
    await view('plan');
    await page.locator('#workspace-source').fill(process.env.EMBER_WORKSPACE_SOURCE);
    await page.getByRole('button',{name:'Prepare workspace scan',exact:true}).click();
    await page.getByRole('button',{name:'Approve read-only scan',exact:true}).click();
    console.log('Reviewed read-only scan complete');
    await view('plan');
    await page.getByText('Observed Git metadata',{exact:true}).click();
    assert((await page.locator('#workspace-status').textContent()).includes('not_inspected'));
    await page.getByRole('button',{name:'Review browser source import',exact:true}).click();
    await page.getByRole('button',{name:'Approve browser source inspection',exact:true}).click();
    await view('plan');
    assert((await page.locator('#workspace-status').textContent()).includes('index.html'));
    assert.equal((await state()).build.completed.length,0);
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('#workspace-status').screenshot({path:path.join(process.env.EMBER_BROWSER_OUTPUT,'browser-import-plan-mobile.png')});
    await page.setViewportSize({width:1500,height:1000});
    await page.getByRole('button',{name:'Review import sandbox copy',exact:true}).click();
    await page.getByRole('button',{name:'Approve import sandbox permissions',exact:true}).click();
    await page.getByRole('button',{name:'Approve exact browser import',exact:true}).click();
    console.log('Reviewed source inspection and exact sandbox copy complete');
    await view('plan');
    await page.getByText('Browser import complete · 3 exact files copied',{exact:true}).waitFor();
    const adopt=page.getByRole('button',{name:'Review imported game changes',exact:true});
    assert(await adopt.isDisabled());assert.equal((await state()).build.completed.length,0);
    await page.reload();await view('plan');
    await page.getByText('Browser import complete · 3 exact files copied',{exact:true}).waitFor();
    const prepared=await page.evaluate(async document=>{const response=await fetch('/api/project-plan',{method:'POST',headers:{'Content-Type':'application/json','X-Ember-Token':sessionStorage.getItem('ember-token')},body:JSON.stringify({session_id:activeSession.id,action:'prepare',document,expected_ref:null})});return {ok:response.ok,body:await response.json()}},JSON.parse(process.env.EMBER_IMPORT_PLAN_DOCUMENT));
    assert(prepared.ok,JSON.stringify(prepared.body));
    await view('chat');await page.getByRole('button',{name:'Approve project plan',exact:true}).click();
    await page.waitForFunction(()=>!busy&&!sending);
    await view('plan');
    await page.waitForFunction(()=>[...document.querySelectorAll('#workspace-status button')].some(b=>b.textContent==='Review imported game changes'&&!b.disabled));
    await adopt.click();
    await page.getByRole('heading',{name:'Imported browser game',exact:true}).waitFor();
    assert.equal((await state()).build.completed.length,0);
    await page.getByRole('button',{name:'Try proposed changes',exact:true}).click();
    const candidate=page.frameLocator('iframe[title="Proposed browser prototype · not applied"]');
    await candidate.getByRole('button',{name:'Start',exact:true}).click();
    assert.equal(await candidate.locator('#score').textContent(),'1');
    await page.getByRole('button',{name:'Approve & play',exact:true}).click();
    await page.getByText('Version 1 · Approved and ready to play',{exact:true}).waitFor();
    console.log('Separate scoped exact build applied');
    const game=page.frameLocator('iframe[title="Approved browser prototype"]');
    await game.getByRole('button',{name:'Start',exact:true}).click();
    await game.locator('body').press('ArrowRight');
    assert.equal(await game.locator('#score').textContent(),'2');
    assert.equal((await state()).project_plan.tasks[0].acceptance,null);
    await page.screenshot({path:path.join(process.env.EMBER_BROWSER_OUTPUT,'imported-game-desktop.png')});
    const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
    mobile=await context.newPage();mobile.on('pageerror',error=>hostErrors.push(error.message));
    await mobile.goto(process.env.EMBER_BROWSER_URL+'#'+process.env.EMBER_BROWSER_TOKEN);
    await mobile.getByText('Version 1 · Approved and ready to play',{exact:true}).waitFor();
    await mobile.locator('.session-item').first().waitFor();
    await mobile.locator('iframe[title="Approved browser prototype"]').scrollIntoViewIfNeeded();
    const mobileStart=mobile.frameLocator('iframe[title="Approved browser prototype"]').getByRole('button',{name:'Start',exact:true});
    await mobileStart.evaluate(button=>document.readyState==='complete'?null:new Promise(resolve=>window.addEventListener('load',resolve,{once:true})));
    await mobileStart.scrollIntoViewIfNeeded();
    await mobileStart.tap();
    await mobile.frameLocator('iframe[title="Approved browser prototype"]').locator('#score').filter({hasText:/^1$/}).waitFor();
    assert.equal(await mobile.frameLocator('iframe[title="Approved browser prototype"]').locator('#score').textContent(),'1');
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mobile.screenshot({path:path.join(process.env.EMBER_BROWSER_OUTPUT,'imported-game-touch.png')});
    await context.close();
    await view('plan');
    const task=page.locator('[data-task-id="task-1"]');
    await task.getByRole('button',{name:'Accept task outcome',exact:true}).click();
    await task.getByText('Outcome accepted by you',{exact:true}).waitFor();
    await view('report');
    const download=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download project handoff',exact:true}).click();
    await (await download).saveAs(path.join(process.env.EMBER_BROWSER_OUTPUT,'imported-project-handoff.zip'));
    assert.deepEqual(hostErrors,[]);
    console.log('PASS: reviewed browser-source import, exact adoption, desktop/touch play, separate acceptance and handoff');
  }catch(error){if(page)await page.screenshot({path:path.join(process.env.EMBER_BROWSER_OUTPUT,'failure.png'),fullPage:true});if(mobile&&!mobile.isClosed())await mobile.screenshot({path:path.join(process.env.EMBER_BROWSER_OUTPUT,'failure-mobile.png'),fullPage:true});throw error;}
  finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)});

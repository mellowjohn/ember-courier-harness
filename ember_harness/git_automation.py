"""Approved model coding hands exact source to the existing local Git verifier.

The two permission reviews are deliberate: variable model output is permitted
only in task-runs; exact generated bytes are then reviewed for private Git work.
The source and Git stages share one task/bug attempt, not two allowances.
"""
from pathlib import Path

from . import chat_build, git_task, polish_runtime, task_run
from .attempts import TaskAttempts
from .core import digest
from .owner_review import load_request, validate_history
from .recovery import read_json, worker_active


def prepare(root, folder, *, finding=None):
    return task_run.prepare(root, folder, finding=finding, git_repair=True)


def source(folder, origin, *, root=None, active=False):
    if (not isinstance(origin, dict) or set(origin) != {'task_run_id', 'index', 'report_sha256'}
            or type(origin['index']) is not int or origin['index'] < 1):
        raise ValueError('Choose an exact independently reviewed automated Git candidate')
    work, h, packet, plan = task_run.load(folder, origin['task_run_id'])
    finished = task_run._finished(h, plan['id'])
    path = work / 'reports' / (str(origin['index']) + '.json')
    if (not plan.get('git_repair') or not finished or finished['status'] != 'ready_review'
            or finished['index'] != origin['index'] or polish_runtime.file_digest(path) != origin['report_sha256']):
        raise ValueError('Automated Git source report changed or is not qualified')
    report = task_run.completed_report(folder, plan['id'], origin['index'])
    if not report or not report['qualified']:
        raise ValueError('An independently qualified coding report is required before Git review')
    files = task_run.candidate_files(work, origin['index'])
    baseline = read_json(work / 'baseline.json')['files']
    if active:
        task_run._unchanged(root, folder, plan)
        task_run.make_worker(root, folder, plan['id']).check()
        if (work / 'stop.json').exists():
            raise ValueError('This automated Git source run was stopped')
    return work, h, packet, plan, report, files, baseline


def linked(folder, task_run_id):
    return [row for row in git_task.requests(folder)
            if (row['payload']['body']['git_task'].get('origin') or {}).get('task_run_id') == task_run_id]


def audited_source(folder, origin):
    """Authority-free identity for cancellation/accounting, even with lost proof."""
    if (not isinstance(origin, dict) or set(origin) != {'task_run_id', 'index', 'report_sha256'}
            or type(origin['index']) is not int or origin['index'] < 1):
        raise ValueError('Choose an audited automated Git handoff')
    h = chat_build.harness(folder); entries = h._entries()
    matches = []
    for event in entries:
        if event['kind'] == 'owner_request':
            packet = load_request(h, event['request_ref'])
            if packet['body'].get('task_run', {}).get('id') == origin['task_run_id']:
                matches.append(packet)
    if len(matches) != 1:
        raise ValueError('One audited source task is required for cancellation or attempt accounting')
    packet = matches[0]; plan = packet['body']['task_run']; work = task_run.run_folder(folder, plan['id'])
    if (not plan.get('git_repair') or plan['session_id'] != Path(folder).name or plan['workspace'] != work.as_posix()
            or not any(e['kind'] == 'task_report' and e['run_id'] == plan['id'] and e['index'] == origin['index']
                       and e['sha256'] == origin['report_sha256'] for e in entries)):
        raise ValueError('Automated Git allocation lacks its audited source report identity')
    validate_history(h, entries)
    return work, h, packet, plan


def advance(root, folder, task_run_id):
    work, h, packet, plan = task_run.load(folder, task_run_id)
    if not plan.get('git_repair'):
        raise ValueError('Choose an automated Git repair task')
    decision = next((e for e in h._entries() if e['kind'] == 'owner_decision' and e['request_ref'] == digest(packet)), None)
    if decision and decision['choice'] == 'decline':
        task_run.attempt_ledger(h, plan, packet).abandon(task_run_id, 'Owner discarded source task permissions')
        from .recovery import atomic_json
        atomic_json(work / 'state.json', dict(status='declined', phase='Source task review discarded', error=None))
        return dict(task_run_id=task_run_id, id=None, request_ref=digest(packet))
    finished = task_run._finished(h, task_run_id)
    if not finished or finished['status'] != 'ready_review':
        raise ValueError('The coding worker must finish independent verification before Git review')
    matches = linked(folder, task_run_id)
    if len(matches) > 1:
        raise ValueError('Conflicting automated Git handoffs need inspection')
    if matches:
        row = matches[0]
        origin = row['payload']['body']['git_task']['origin']
        if row['decision'] and row['decision']['choice'] == 'decline':
            Ledger(folder, origin).abandon(task_run_id, 'Owner discarded exact Git verification permissions')
        else:
            source(folder, origin)
        return dict(task_run_id=task_run_id, id=row['payload']['body']['git_task']['id'], request_ref=row['ref'])
    index = finished['index']
    origin = dict(task_run_id=task_run_id, index=index,
                  report_sha256=polish_runtime.file_digest(work / 'reports' / (str(index) + '.json')))
    _, _, _, _, report, files, baseline = source(folder, origin, root=root, active=True)
    prepared = git_task.prepare(root, folder, candidate_files=files, baseline_files=baseline,
        expected_manifest=plan['base_manifest'], origin=origin, goal=plan['goal'])
    if (work / 'stop.json').exists():
        git_task.respond(root, folder, prepared['id'], 'decline', 'Owner stopped this automated repair before Git verification')
    return dict(task_run_id=task_run_id, **prepared)


class Ledger:
    """Continue the same already allocated source attempt through Git proof."""
    def __init__(self, folder, origin):
        self.folder, self.origin = Path(folder), origin
        # Cancellation uses audited task identity, not a positive source claim.
        # A missing/tampered report must block execution, never trap its allowance.
        self.work, self.h, self.packet, self.plan = audited_source(folder, origin)
        self.inner = task_run.attempt_ledger(self.h, self.plan, self.packet)

    def begin(self, run_id, index):
        source(self.folder, self.origin)
        return self.inner.begin(self.plan['id'], self.origin['index'])

    def finish(self, attempt, report, path):
        source(self.folder, self.origin)
        if self.plan.get('kind') == 'finding':
            # Qualified finding attempts remain open until explicit C3 closure.
            # A failed clean Git witness ends this same attempt without fabricating
            # a second canonical bug or a successful browser closure.
            if not report['qualified']:
                self.inner.abandon(self.plan['id'], 'Independent clean Git verification failed; inspect its retained report')
            return
        return self.inner.finish(attempt, report, path)

    def abandon(self, run_id, reason):
        return self.inner.abandon(self.plan['id'], reason)


def decorate_task(folder, plan, row, *, packet=None):
    if not plan.get('git_repair'):
        return
    row['git_repair'] = plan['git_repair']
    matches = linked(folder, plan['id'])
    if not matches:
        h = chat_build.harness(folder)
        if packet is None:
            packet = task_run.load(folder, plan['id'])[2]
        source_decision = next((event for event in h._entries() if event['kind'] == 'owner_decision' and event['request_ref'] == digest(packet)), None)
        if source_decision:
            choice = source_decision['choice']
            pending = any(item.get('outcome', item.get('status')) == 'running' for item in row['attempts']['attempts'])
            if choice == 'decline':
                row.update(status='ready_review' if pending else 'declined', git_stage='cancellation_needed' if pending else 'declined')
                return
            if row['status'] == 'awaiting_approval':
                row.update(status='interrupted', phase='Source permissions recorded; resume the approved worker')
        finished = task_run._finished(chat_build.harness(folder), plan['id'])
        row['git_stage'] = (row['status'] if row['status'] in ('declined', 'stopped', 'awaiting_decision', 'scope_inactive', 'inspection_required')
            else 'review_needed' if finished and finished['status'] == 'ready_review' else 'awaiting_source')
        return
    if len(matches) != 1:
        row.update(status='inspection_required', error='Conflicting automated Git handoffs')
        return
    request = matches[0]; git_id = request['payload']['body']['git_task']['id']
    work, h, packet, git_plan = git_task.load(folder, git_id)
    state = git_task._review_state(work, h, packet)
    if state['status'] == 'running' and not worker_active(work):
        state['status'] = 'interrupted'
    row.update(git_run_id=git_id, git_stage=state['status'])
    if any(e['kind'] == 'git_task_promoted' and e['run_id'] == git_id for e in h._entries()):
        row['git_stage'] = 'promoted'
    if request['decision'] and request['decision']['choice'] == 'decline':
        pending = any(item.get('outcome', item.get('status')) == 'running' for item in row['attempts']['attempts'])
        row.update(status='ready_review' if pending else 'stopped', git_stage='cancellation_needed' if pending else 'declined')
    elif state['status'] == 'stopped':
        row['status'] = 'stopped'
    elif state['status'] == 'needs_changes':
        row['status'] = 'awaiting_decision'
    promoted = next((e for e in h._entries() if e['kind'] == 'task_run_promoted' and e['run_id'] == plan['id']), None)
    if plan.get('kind') == 'finding' and promoted and row['status'] != 'stopped':
        proposal = next((request for request in chat_build.list_requests(folder) if request['ref'] == promoted['request_ref']), None)
        if proposal and proposal['decision'] and proposal['decision']['choice'] == 'decline':
            pending = any(item.get('outcome', item.get('status')) == 'running' for item in row['attempts']['attempts'])
            row.update(status='ready_review' if pending else 'stopped', git_stage='application_declined')


def history(root, folder, *, tasks=None):
    rows = []
    for task in task_run.history(root, folder) if tasks is None else tasks:
        if not task.get('git_repair'):
            continue
        stage = task['status'] if task['status'] in ('inspection_required', 'scope_inactive', 'stopped', 'declined') else task.get('git_stage', task['status'])
        rows.append(dict(task_run_id=task['id'], git_run_id=task.get('git_run_id'),
            status=stage, source_status=task['status'],
            goal=task['goal'], error=task.get('error'), attempts=task['attempts'],
            finding=task.get('finding'), request_ref=task['request_ref'],
            basis='Approved sequential model coding and independent browser review, then separately approved clean Git verification. Human acceptance remains pending.'))
    return rows


def stop(root, folder, task_run_id):
    matches = linked(folder, task_run_id)
    for row in matches:
        git_id = row['payload']['body']['git_task']['id']
        if row['decision'] and row['decision']['choice'] == 'approve':
            git_task.stop(root, folder, git_id)
        elif not row['decision']:
            git_task.respond(root, folder, git_id, 'decline', 'Owner stopped the automated Git repair')
    if matches:
        work, h, packet, plan = audited_source(folder, matches[0]['payload']['body']['git_task']['origin'])
        return task_run._stop_loaded(root, folder, work, h, packet, plan)
    return task_run.stop(root, folder, task_run_id)


def witness(folder, task_run_id, proposal_ref, *, _checking_closure=False):
    matches = linked(folder, task_run_id)
    if len(matches) != 1:
        raise ValueError('One exact clean Git witness is required for this finding repair')
    request = matches[0]; run_id = request['payload']['body']['git_task']['id']
    report = git_task.completed_report(folder, run_id, _checking_closure=_checking_closure)
    work, h, packet, plan = git_task.load(folder, run_id)
    promoted = next((e for e in h._entries() if e['kind'] == 'git_task_promoted' and e['run_id'] == run_id), None)
    if not report or not report['qualified'] or not promoted or promoted['request_ref'] != proposal_ref:
        raise ValueError('A qualified clean Git head and its exact applied proposal are required before finding closure')
    return dict(run_id=run_id, base=report['base'], head=report['head'],
        source_run_id=task_run_id, source_index=plan['origin']['index'],
        report_sha256=polish_runtime.file_digest(work / 'report.json'),
        gameplay_plan_sha256=report['gameplay_plan_sha256'])
